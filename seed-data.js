// segmento provável pelo nome do cliente
export function segmentoDe(nome) {
  const n = nome.toLowerCase();
  if (/frigor|avícola|granja|açougue|pescad|peixaria/.test(n)) return 1;
  if (/latic|queijaria|leite/.test(n)) return 2;
  if (/restaurante|padaria|confeitaria|buffet|cozinha|pizzaria|hamburgueria|açaí|sorvet|cervejaria/.test(n)) return 3;
  if (/hospital|clínica|farmácia|laborat|hemocentro|vacinar|odonto/.test(n)) return 4;
  if (/hotel|pousada/.test(n)) return 5;
  if (/distribuidora|atacad/.test(n)) return 6;
  if (/indústria|polpas/.test(n)) return 7;
  return 0;
}

